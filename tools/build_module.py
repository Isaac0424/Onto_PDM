def scope_selectors(sel):
    out = []
    for s in sel.split(','):
        s = s.strip()
        if not s:
            continue
        if s in (':root', 'html', 'body', 'html, body'):
            out.append('.xs-root')
        elif s == '*':
            out.append('.xs-root, .xs-root *')
        elif s.startswith(':root'):
            out.append('.xs-root' + s[5:])
        else:
            out.append('.xs-root ' + s)
    return ', '.join(out)

def scope_block(text):
    res, i = [], 0
    while i < len(text):
        j = text.find('{', i)
        if j < 0:
            res.append(text[i:]); break
        prelude = text[i:j].strip()
        depth, k = 1, j + 1
        while depth:
            if text[k] == '{': depth += 1
            elif text[k] == '}': depth -= 1
            k += 1
        inner = text[j + 1:k - 1]
        if prelude.startswith('@media'):
            q = prelude[len('@media'):].strip()
            if 'width' in q:           # layout breakpoints follow the box the studio sits in, not the window
                res.append('@container xs ' + q + ' {' + scope_block(inner) + '}\n')
            else:
                res.append(prelude + ' {' + scope_block(inner) + '}\n')
        elif prelude.startswith('@keyframes'):
            res.append(prelude.replace('@keyframes ', '@keyframes xs-') + ' {' + inner + '}\n')
        else:
            res.append(scope_selectors(prelude) + ' {' + inner + '}\n')
        i = k
    return ''.join(res)

scoped = scope_block(css)
scoped = scoped.replace('animation: slide ', 'animation: xs-slide ')
