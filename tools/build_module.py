app = must_replace(app, "window.addEventListener('unhandledrejection', e => { setAiStatus('오류: ' + (e.reason && e.reason.message || e.reason), true); });\n", "", 'err2')
app = must_replace(app, "function frame(now) {\n  requestAnimationFrame(frame);", "function frame(now) {\n  if (destroyed) return;\n  rafId = requestAnimationFrame(frame);", 'raf')
app = must_replace(app, "const r = await fetch('sample-as1.stp');", "const r = await fetch(options.sampleStepUrl);", 'sample')
app = must_replace(app, "setInterval(() => {", "const clockId = setInterval(() => {", 'clock')
# events for the host page
