"""Generate the embeddable ES-module package (explode-studio/) from the same sources the artifact
page is built from (core.js, app.js, demo.js, body.html, head.html). Run after any change:

    python3 tools/build_module.py
"""
import os, re, shutil, json, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'source') if os.path.isdir(os.path.join(ROOT, 'source')) else ROOT
