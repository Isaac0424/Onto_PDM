read = lambda n: open(os.path.join(SRC, n), encoding='utf-8').read()

def must_replace(text, old, new, label):
    if old not in text:
        raise SystemExit(f'build_module: pattern not found ({label}): {old[:70]!r}')
    return text.replace(old, new, 1)

# ---------- core.js → src/core.js (named exports) ----------
core = read('core.js')
